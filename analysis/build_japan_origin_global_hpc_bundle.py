#!/usr/bin/env python3
"""Build a restartable Slurm bundle for the 302-sample global Japanese-origin tree.

Input is the source-safe 302-row panel generated by
``build_japan_origin_global_public_panel.py``.  The bundle uses safe synthetic
tip IDs so commas/spaces/synonyms in source metadata cannot break shell parsing,
while preserving an explicit tip map.

Primary mapping is BWA in HybPiper 2.3.4; BLASTx is a predeclared mapping
sensitivity.  Primary tree admission is the frozen conservative-241 universe
intersected with current occupancy >=0.80 and zero current paralog warnings.
If <100 loci survive, execution stops rather than relaxing filters post hoc.
"""
from __future__ import annotations
import argparse,csv,json,shlex
from pathlib import Path

REF_SHA='77d510ef101d08a7a23a4df391d077d3b7f75482c66f7f4bea6d32cf290ced2c'
EXPECTED_SAMPLES=302
EXPECTED_RUNS=303

def clean(x):return str(x or '').strip()
def read_panel(path):
    with path.open(encoding='utf-8-sig',newline='') as h:rows=[{k:clean(v) for k,v in r.items()} for r in csv.DictReader(h)]
    req={'panel_id','source_study','assay','analysis_taxon_label','voucher','biosample','run_accessions','run_count'}
    if not rows or not req<=set(rows[0]):raise ValueError(f'global panel requires columns {sorted(req)}')
    if len(rows)!=EXPECTED_SAMPLES:raise ValueError(f'expected {EXPECTED_SAMPLES} rows, found {len(rows)}')
    if len({r['panel_id'] for r in rows})!=EXPECTED_SAMPLES:raise ValueError('panel_id values are not unique')
    if sum(int(r['run_count']) for r in rows)!=EXPECTED_RUNS:raise ValueError('public run-count drift')
    for r in rows:
        runs=[x for x in r['run_accessions'].split('|') if x]
        if len(runs)!=int(r['run_count']) or any(not x.startswith('SRR') for x in runs):raise ValueError(f'invalid run list for {r["panel_id"]}')
    return rows
def write(path,text,mode=0o644):path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text,encoding='utf-8');path.chmod(mode)
def sample_tsv(path,rows):
    fields=['index','tip_id','panel_id','source_study','assay','analysis_taxon_label','voucher','biosample','run_accessions','run_count']
    with path.open('w',encoding='utf-8',newline='') as h:
        w=csv.DictWriter(h,fieldnames=fields,delimiter='\t',lineterminator='\n');w.writeheader()
        for i,r in enumerate(rows):
            w.writerow({'index':i,'tip_id':f'JOG{i+1:04d}','panel_id':r['panel_id'],'source_study':r['source_study'],'assay':r['assay'],'analysis_taxon_label':r['analysis_taxon_label'],'voucher':r['voucher'],'biosample':r['biosample'],'run_accessions':r['run_accessions'],'run_count':r['run_count']})
