def submit_data(mode):
    h='02_hybpiper_bwa_slurm.sh' if mode=='bwa' else '02b_hybpiper_blastx_slurm.sh'
    return f'''#!/usr/bin/env bash
set -euo pipefail
prep=$(sbatch --parsable 00_prepare_inputs_slurm.sh); fetch=$(sbatch --parsable --dependency=afterok:$prep 01_fetch_trim_slurm.sh); hyb=$(sbatch --parsable --dependency=afterok:$fetch {h}); qc=$(sbatch --parsable --dependency=afterok:$hyb --export=ALL,MODE={mode} 03_retrieve_qc_slurm.sh); printf 'prepare=%s\nfetch=%s\nhybpiper=%s\nqc=%s\n' "$prep" "$fetch" "$hyb" "$qc"
'''
def submit_tree():return '''#!/usr/bin/env bash
set -euo pipefail
MODE="${MODE:-bwa}"; prep=$(sbatch --parsable --export=ALL,MODE="$MODE" 04_prepare_tree_inputs_slurm.sh); aln=$(sbatch --parsable --dependency=afterok:$prep --export=ALL,MODE="$MODE" 05_align_loci_slurm.sh); gene=$(sbatch --parsable --dependency=afterok:$aln --export=ALL,MODE="$MODE" 06_gene_trees_slurm.sh); con=$(sbatch --parsable --dependency=afterok:$aln --export=ALL,MODE="$MODE" 07_concat_tree_slurm.sh); acc=$(sbatch --parsable --dependency=afterok:$gene:$con --export=ALL,MODE="$MODE" 08_accept_tree_slurm.sh); printf 'prep=%s\nalign=%s\ngene=%s\nconcat=%s\naccept=%s\n' "$prep" "$aln" "$gene" "$con" "$acc"
'''
def main():
    p=argparse.ArgumentParser();p.add_argument('--panel',type=Path,required=True);p.add_argument('--outdir',type=Path,required=True);a=p.parse_args();rows=read_panel(a.panel);a.outdir.mkdir(parents=True,exist_ok=True);sample_tsv(a.outdir/'sample_manifest.tsv',rows)
    # CSV copy with safe tree IDs plus metadata; generic tree/QC scripts consume this.
    tsv=list(csv.DictReader((a.outdir/'sample_manifest.tsv').open(encoding='utf-8'),delimiter='\t'))
    with (a.outdir/'sample_manifest.csv').open('w',encoding='utf-8',newline='') as h:
        w=csv.DictWriter(h,fieldnames=list(tsv[0]));w.writeheader();w.writerows(tsv)
    write(a.outdir/'env.yml',env_yml())
    scripts={'00_prepare_inputs_slurm.sh':prep(),'01_fetch_trim_slurm.sh':fetch(),'02_hybpiper_bwa_slurm.sh':hyb('bwa'),'02b_hybpiper_blastx_slurm.sh':hyb('blastx'),'03_retrieve_qc_slurm.sh':qc(),'04_prepare_tree_inputs_slurm.sh':treeprep(),'05_align_loci_slurm.sh':align(),'06_gene_trees_slurm.sh':gene(),'07_concat_tree_slurm.sh':concat(),'08_accept_tree_slurm.sh':accept(),'submit_bwa_chain.sh':submit_data('bwa'),'submit_blastx_chain.sh':submit_data('blastx'),'submit_tree_chain.sh':submit_tree()}
    for n,t in scripts.items():write(a.outdir/n,t,0o755)
    m={'bundle_version':'japan_origin_global_hpc_bundle_v1','biological_samples':302,'public_runs':303,'safe_tip_ids':True,'primary_mapping':'bwa','mapping_sensitivity':'blastx','hybpiper_version':'2.3.4','frozen_primary_locus_universe':241,'primary_current_occupancy_gate':0.80,'current_paralog_gate':'zero HybPiper >1-copy warnings across all 302 samples','minimum_primary_loci_to_launch':100,'automatic_filter_relaxation_allowed':False,'tree_products':['per-locus IQ-TREE gene trees','concatenated IQ-TREE ML tree'],'coalescent_stage_input':'per-locus gene-tree directory retained for ASTRAL/coalescent sensitivity','tree_completed':False,'japanese_origin_inference_completed':False,'new_china_sampling_freeze_allowed':False}
    write(a.outdir/'execution_manifest.json',json.dumps(m,indent=2)+'\n');print(json.dumps(m,indent=2));return 0
if __name__=='__main__':raise SystemExit(main())
